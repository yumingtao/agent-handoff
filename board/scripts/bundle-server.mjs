import { build } from 'esbuild';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');

await build({
  entryPoints: [join(ROOT, 'src', 'server.mjs')],
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  outfile: join(ROOT, 'electron', 'server.mjs'),
  external: [
    // Node.js built-ins that should not be bundled
    'node:*',
  ],
  banner: {
    js: '// Bundled handoff-board server — DO NOT EDIT (generated by esbuild)',
  },
  logLevel: 'info',
  keepNames: true,
});

console.log('Server bundle created: electron/server.mjs');
